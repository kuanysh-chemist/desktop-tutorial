/**
 * Пул приёмов для роли с учётом характера темы.
 *
 * Сначала берутся приёмы, прямо привязанные к типу темы, — они точнее.
 * Если таких меньше трёх, добавляются универсальные, иначе выбор
 * схлопывается к одному и тому же приёму для всех тем одного типа.
 */
export function activePool(role: MethodRole, kind: TopicKind): ActiveMethod[] {
  const byRole = ACTIVE_METHODS.filter((m) => m.role === role && !m.requires);
  const specific = byRole.filter((m) => m.kinds.includes(kind));
  const universal = byRole.filter((m) => m.kinds.length === 0);
  return specific.length >= 3 ? specific : [...specific, ...universal];
}

/**
 * Приём рефлексии, который замыкает начало урока: если класс заполнял таблицу
 * ЗХУ или лист утверждений, к нему и нужно вернуться. Если такого приёма нет,
 * рефлексия выбирается из общего пула.
 */
export function boundReflection(activationId: string): ActiveMethod | undefined {
  return ACTIVE_METHODS.find(
    (m) => m.role === "reflection" && m.requires === activationId,
  );
}

export function activeById(id: string): ActiveMethod | undefined {
  return ACTIVE_METHODS.find((m) => m.id === id);
}
